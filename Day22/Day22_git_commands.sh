# ============================================================
# Day 22 — Git 基础：命令序列（参考，不可直接执行！）
# ============================================================
# 注意：本文件是 Git 命令的学习参考，不是可执行脚本。
# 请逐条阅读注释，然后在终端里手动输入练习。
# 每条命令前面加了注释 #  表示需要在终端输入的命令。
# ============================================================

# ============================================================
# 第一步：创建练习目录并初始化仓库
# ============================================================

#   # 在你的用户目录下创建练习文件夹
#   mkdir ~/git-practice
#   cd ~/git-practice
#
#   # 初始化 Git 仓库（会在当前目录下创建隐藏的 .git 文件夹）
#   git init
#   # 输出: Initialized empty Git repository in ...
#
#   # 查看状态——此时应该显示没有提交记录
#   git status
#   # 输出: On branch main, No commits yet

# ============================================================
# 第二步：第一次提交（创建文件 → add → commit）
# ============================================================

#   # 创建第一个文件
#   echo "# Git 练习项目" > README.md
#
#   # 用 git status 查看——README.md 显示为 "Untracked files"（未跟踪）
#   git status
#
#   # 把 README.md 加入暂存区（staging area）
#   git add README.md
#
#   # 再次 status——README.md 变成 "Changes to be committed"（准备提交）
#   git status
#
#   # 提交到仓库，-m 后面是提交说明
#   git commit -m "feat: 初始化项目，添加 README"
#
#   # 查看提交历史（一行一条，简洁模式）
#   git log --oneline
#   # 输出类似: abc1234 feat: 初始化项目，添加 README

# ============================================================
# 第三步：修改文件 + 多次提交
# ============================================================

#   # 追加内容到 README.md
#   echo "" >> README.md
#   echo "这是一个 Git 练习项目。" >> README.md
#
#   # 用 git diff 查看具体改了什么（+ 表示新增行）
#   git diff
#
#   # add + commit
#   git add README.md
#   git commit -m "docs: 添加项目描述"
#
#   # 创建新文件
#   echo "print('Hello Git')" > hello.py
#   git add hello.py
#   git commit -m "feat: 添加 hello.py"
#
#   # 查看完整历史（应该看到 3 条提交，从新到旧排列）
#   git log --oneline

# ============================================================
# 第四步：理解 git diff 的两种用法
# ============================================================

#   # 修改 hello.py（不 add）
#   echo "print('Goodbye')" >> hello.py
#
#   # git diff（无参数）：比较 工作区 vs 暂存区（最后一次 commit 的快照）
#   # 会显示新增的 print('Goodbye') 行
#   git diff
#
#   # git diff --staged：比较 暂存区 vs 仓库
#   # 由于还没 add，所以没有输出（暂存区=仓库）
#   git diff --staged
#
#   # 现在 add 后再比较
#   git add hello.py
#   git diff            # 无输出——工作区和暂存区现在一致
#   git diff --staged   # 有输出——暂存区比仓库多了 print('Goodbye')
#
#   # 提交这次改动
#   git commit -m "feat: hello.py 添加 Goodbye 输出"
#
#   # 查看最终历史
#   git log --oneline

# ============================================================
# 第五步：清理练习目录
# ============================================================

#   cd ~
#   rm -rf ~/git-practice

# ============================================================
# 小结：你学会了什么？
# ============================================================
# 1. git init       — 创建仓库
# 2. git status     — 查看状态（改了什么、哪些暂存了）
# 3. git add        — 把改动加入暂存区
# 4. git commit -m  — 把暂存区提交到仓库
# 5. git log        — 查看提交历史
# 6. git diff       — 查看工作区 vs 暂存区的差异
# 7. git diff --staged — 查看暂存区 vs 仓库的差异
#
# 这 7 个命令覆盖了 Git 80% 的日常使用场景。
